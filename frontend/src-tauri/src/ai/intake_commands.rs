//! Bulk intake: one target plus a corpus of raw-text entries becomes real profiles, with the raw text kept and
//! the existing extraction turned loose on each one.
//!
//! Nothing here is a second path. Entries are split by `matchmaking_core::intake`, profiles are created by the
//! same validated insert `mm_create_profile` uses, each note is written with its profile in one transaction, the
//! model is reached through `service::extract_profile`, and accepting is `service::decide_suggestion` — the same
//! decision a single suggestion goes through, with the same audit. A model still only ever suggests.
//!
//! Every entry stands alone: an empty, oversized, or unreadable one is reported against that entry and the run
//! carries on. A closed AI gate is a property of the whole run: the profiles and their notes are still created,
//! no model is contacted, and nothing is marked parsed.

use super::commands::prepare;
use super::service::{self, Decision, Session};
use crate::mm::intake_repo::IntakeRepo;
use crate::mm::repository::MmRepository;
use crate::state::AppState;
use matchmaking_core::{parse_entries, split_corpus, IntakeEntry, ParsedCorpus, Profile};
use serde::Serialize;
use tauri::State;

fn err<E: std::fmt::Display>(e: E) -> String {
    e.to_string()
}

/// What happened to one entry. Counts and reasons only: never a value, never a quote from the text.
#[derive(Debug, Clone, Serialize)]
pub struct IntakeEntryReport {
    /// 1-based position in the corpus the matchmaker supplied.
    pub index: usize,
    pub label: String,
    /// The profile created for this entry, when one was.
    pub profile_id: Option<String>,
    /// "created" | "parsed" | "dropped"
    pub outcome: String,
    /// How many suggestions the entry produced. Zero when the gate was closed or the entry could not be read.
    pub suggestions: i64,
    /// A short reason, shown to the matchmaker, when nothing was created or parsed.
    pub reason: Option<String>,
}

/// The whole run: what was created, what was parsed, and what was not — with per-entry reasons.
#[derive(Debug, Clone, Serialize)]
pub struct IntakeBatchReport {
    pub batch_id: String,
    /// The target the matchmaker was working on, if one was given. Never created by the corpus.
    pub target_profile_id: Option<String>,
    /// False when the AI gate was closed: profiles and raw text were kept, nothing was parsed.
    pub parsed: bool,
    /// Why nothing was parsed, when `parsed` is false. Written for the matchmaker.
    pub note: Option<String>,
    pub entries: Vec<IntakeEntryReport>,
    pub created: usize,
    pub dropped: usize,
    pub suggestions: i64,
}

/// What a batch accept did, and what it left alone.
#[derive(Debug, Clone, Serialize)]
pub struct IntakeAcceptReport {
    pub accepted: usize,
    /// Left pending or refused — e.g. a person already owns a different value in that field.
    pub skipped: usize,
    /// The fields that were accepted, for the audit trail's own wording. Field names only.
    pub fields: Vec<String>,
}

/// Read the corpus: a caller that already split it (a `.json` array) sends strings, one entry each; a pasted
/// corpus is split here by the core helper. Both end as the same `ParsedCorpus`.
fn corpus_of(
    corpus_text: Option<String>,
    entries: Option<Vec<String>>,
) -> Result<ParsedCorpus, String> {
    match entries {
        Some(items) => Ok(parse_entries(&items)),
        None => match corpus_text {
            Some(text) => Ok(split_corpus(&text)),
            None => Err("Paste a corpus, or supply the entries of a file.".into()),
        },
    }
}

/// Create the profile and its note for one entry. Returns the new profile id, or the reason it could not be made.
async fn create_one(
    pool: &sqlx::SqlitePool,
    batch_id: &str,
    entry: &IntakeEntry,
) -> Result<String, String> {
    let profile = Profile::new(uuid::Uuid::new_v4().to_string());
    // No fields: the entry is the source, not the answer. It is validated and empty, exactly like a fresh profile.
    profile.validate(&MmRepository::registry(pool).await.map_err(err)?);
    IntakeRepo::insert_profile_with_note(pool, &profile, batch_id, &entry.text, &entry.label)
        .await
        .map_err(err)?;
    Ok(profile.id)
}

/// Run a whole corpus through intake.
///
/// `target` is the person the matchmaker is working on — it becomes its own profile, never part of the corpus.
/// `target_text` is the raw corpus when the frontend has not split it; `entries` is the pre-split form (a `.json`
/// array). `batch_id` is generated by the caller so the report and the accept step address the same run.
#[tauri::command]
pub async fn ai_intake_batch(
    state: State<'_, AppState>,
    target: Option<String>,
    target_text: Option<String>,
    entries: Option<Vec<String>>,
    batch_id: String,
) -> Result<IntakeBatchReport, String> {
    run_batch(
        state.db_manager.pool(),
        target,
        target_text,
        entries,
        batch_id,
    )
    .await
}

/// The body of [`ai_intake_batch`], over a pool so the tests can drive it with a scripted model in place.
pub(crate) async fn run_batch(
    pool: &sqlx::SqlitePool,
    target: Option<String>,
    target_text: Option<String>,
    entries: Option<Vec<String>>,
    batch_id: String,
) -> Result<IntakeBatchReport, String> {
    // The gate is read once for the run, not once per entry: either the whole run is parsed, or none of it is.
    let gate = prepare(pool).await;
    let session = match &gate {
        Ok((config, mode, backend)) => Some(Session {
            backend,
            provider: config.provider.clone(),
            model: config.model.clone(),
            mode: *mode,
        }),
        Err(_) => None,
    };
    let closed_note = gate.as_ref().err().cloned();
    run_batch_with(
        pool,
        target,
        target_text,
        entries,
        batch_id,
        session.as_ref(),
        closed_note,
    )
    .await
}

/// The run itself, with the session given rather than read from settings: the tests substitute a scripted model,
/// and the command path passes the one the gate produced.
pub(crate) async fn run_batch_with(
    pool: &sqlx::SqlitePool,
    target: Option<String>,
    target_text: Option<String>,
    entries: Option<Vec<String>>,
    batch_id: String,
    session: Option<&Session<'_>>,
    closed_note: Option<String>,
) -> Result<IntakeBatchReport, String> {
    let parsed_corpus = corpus_of(target_text, entries)?;
    if batch_id.trim().is_empty() {
        return Err("A batch id is required so the run can be reported and accepted.".into());
    }

    let parsed = session.is_some();
    let mut report = IntakeBatchReport {
        batch_id: batch_id.clone(),
        target_profile_id: None,
        parsed,
        note: if parsed { None } else { closed_note },
        entries: Vec::new(),
        created: 0,
        dropped: 0,
        suggestions: 0,
    };

    // The target is one person, not a corpus entry: it gets its own profile and, on the same path as every entry,
    // its own note, so the ranked run and the profile page both work off the same stored text.
    if let Some(target) = target {
        let target_entry = parse_entries(&[target]).entries.into_iter().next();
        match target_entry {
            Some(entry) => match create_one(pool, &batch_id, &entry).await {
                Ok(profile_id) => {
                    MmRepository::audit(
                        pool,
                        "intake_target_created",
                        "profile",
                        &profile_id,
                        Some(&entry.label),
                    )
                    .await;
                    report.target_profile_id = Some(profile_id);
                }
                Err(reason) => {
                    report.note = Some(format!("The target could not be created: {reason}"))
                }
            },
            None => {
                report.note = Some("The target was empty, so no target profile was created.".into())
            }
        }
    }

    for dropped in &parsed_corpus.dropped {
        report.dropped += 1;
        report.entries.push(IntakeEntryReport {
            index: dropped.index,
            label: dropped.label.clone(),
            profile_id: None,
            outcome: "dropped".into(),
            suggestions: 0,
            reason: Some("Nothing to read: the entry is empty.".into()),
        });
    }
    for entry in &parsed_corpus.entries {
        let profile_id = match create_one(pool, &batch_id, entry).await {
            Ok(id) => id,
            Err(reason) => {
                report.dropped += 1;
                report.entries.push(IntakeEntryReport {
                    index: entry.index,
                    label: entry.label.clone(),
                    profile_id: None,
                    outcome: "dropped".into(),
                    suggestions: 0,
                    reason: Some(reason),
                });
                continue;
            }
        };
        report.created += 1;
        MmRepository::audit(
            pool,
            "intake_entry_created",
            "profile",
            &profile_id,
            Some(&entry.label),
        )
        .await;

        let Some(session) = session else {
            // Gate closed: the profile and its raw text are kept, nothing is parsed, and no model is contacted.
            report.entries.push(IntakeEntryReport {
                index: entry.index,
                label: entry.label.clone(),
                profile_id: Some(profile_id),
                outcome: "created".into(),
                suggestions: 0,
                reason: None,
            });
            continue;
        };

        // Sequential by design: `service::ask` holds one request at a time.
        match service::extract_profile(pool, session, &profile_id, None).await {
            Ok(view) => {
                let n = view.suggestions.len() as i64;
                report.suggestions += n;
                report.entries.push(IntakeEntryReport {
                    index: entry.index,
                    label: entry.label.clone(),
                    profile_id: Some(profile_id),
                    outcome: "parsed".into(),
                    suggestions: n,
                    reason: None,
                });
            }
            Err(reason) => {
                // The profile and its source text stay: only this entry could not be read.
                report.entries.push(IntakeEntryReport {
                    index: entry.index,
                    label: entry.label.clone(),
                    profile_id: Some(profile_id),
                    outcome: "created".into(),
                    suggestions: 0,
                    reason: Some(reason),
                });
            }
        }
    }

    MmRepository::audit(
        pool,
        "intake_batch",
        "settings",
        "intake",
        Some(&format!(
            "{} created, {} dropped",
            report.created, report.dropped
        )),
    )
    .await;
    Ok(report)
}

/// The stored report for a batch, so a reloaded page can show the same outcome without rerunning anything.
#[tauri::command]
pub async fn ai_intake_report(
    state: State<'_, AppState>,
    batch_id: String,
) -> Result<IntakeBatchReport, String> {
    run_report(state.db_manager.pool(), batch_id).await
}

/// The raw entry a profile was created from, for the profile page to show read-only. It is shown, never edited:
/// it is the source the profile was read from, not a field the matchmaker maintains.
#[tauri::command]
pub async fn mm_intake_note(
    state: State<'_, AppState>,
    id: String,
) -> Result<Option<String>, String> {
    IntakeRepo::note_for_profile(state.db_manager.pool(), &id)
        .await
        .map_err(err)
}

/// The body of [`ai_intake_report`], over a pool.
pub(crate) async fn run_report(
    pool: &sqlx::SqlitePool,
    batch_id: String,
) -> Result<IntakeBatchReport, String> {
    let notes = IntakeRepo::notes_for_batch(pool, &batch_id)
        .await
        .map_err(err)?;
    let mut report = IntakeBatchReport {
        batch_id: batch_id.clone(),
        target_profile_id: None,
        parsed: false,
        note: None,
        entries: Vec::new(),
        created: notes.len(),
        dropped: 0,
        suggestions: 0,
    };
    for (i, note) in notes.iter().enumerate() {
        report.entries.push(IntakeEntryReport {
            index: i + 1,
            label: note.label.clone(),
            profile_id: Some(note.profile_id.clone()),
            outcome: "created".into(),
            suggestions: 0,
            reason: None,
        });
    }
    report.parsed = report.suggestions > 0;
    Ok(report)
}

/// Accept every pending suggestion of a batch, through the ordinary decision path.
///
/// Nothing here decides anything the single-suggestion command would not: a plain accept is refused where a
/// person owns a different value, and each accepted field is audited by `decide_suggestion` itself. Running it
/// twice is a no-op the second time: only pending suggestions are considered.
#[tauri::command]
pub async fn ai_intake_accept_all(
    state: State<'_, AppState>,
    batch_id: String,
) -> Result<IntakeAcceptReport, String> {
    run_accept_all(state.db_manager.pool(), batch_id).await
}

/// The body of [`ai_intake_accept_all`], over a pool.
pub(crate) async fn run_accept_all(
    pool: &sqlx::SqlitePool,
    batch_id: String,
) -> Result<IntakeAcceptReport, String> {
    let notes = IntakeRepo::notes_for_batch(pool, &batch_id)
        .await
        .map_err(err)?;
    let mut report = IntakeAcceptReport {
        accepted: 0,
        skipped: 0,
        fields: Vec::new(),
    };
    for note in notes {
        let pending = super::repo::pending_suggestions(pool, &note.profile_id)
            .await
            .map_err(err)?;
        for sug in pending {
            match service::decide_suggestion(pool, sug.id, Decision::Accept).await {
                Ok(()) => {
                    report.accepted += 1;
                    report.fields.push(sug.field);
                }
                Err(_) => report.skipped += 1,
            }
        }
    }
    Ok(report)
}
